$ErrorActionPreference = 'Stop'
$defs = Get-Content (Join-Path $PSScriptRoot 'file-associations.json') -Raw | ConvertFrom-Json
$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('; Generated by installer/Generate-Associations.ps1. Do not edit by hand.')
$lines.Add('[Registry]')
foreach ($def in $defs) {
    $progId = 'SoundAppR.' + $def.group
    $lines.Add(('Root: HKA; Subkey: "Software\Classes\{0}"; ValueType: string; ValueName: ""; ValueData: "{1}"; Tasks: associate; Flags: uninsdeletekey' -f $progId, $def.description))
    $lines.Add(('Root: HKA; Subkey: "Software\Classes\{0}\DefaultIcon"; ValueType: string; ValueName: ""; ValueData: "{{app}}\icons\{1}"; Tasks: associate; Flags: uninsdeletekey' -f $progId, $def.icon))
    $lines.Add(('Root: HKA; Subkey: "Software\Classes\{0}\shell\open\command"; ValueType: string; ValueName: ""; ValueData: """{{app}}\soundapp_r.exe"" ""%1"""; Tasks: associate; Flags: uninsdeletekey' -f $progId))
    foreach ($ext in $def.extensions) {
        $lines.Add(('Root: HKA; Subkey: "Software\Classes\.{0}\OpenWithProgids"; ValueType: string; ValueName: "{1}"; ValueData: ""; Tasks: associate; Flags: uninsdeletevalue' -f $ext, $progId))
        $lines.Add(('Root: HKA; Subkey: "Software\SoundAppR\Capabilities\FileAssociations"; ValueType: string; ValueName: ".{0}"; ValueData: "{1}"; Tasks: associate; Flags: uninsdeletevalue' -f $ext, $progId))
    }
}
$out = Join-Path $PSScriptRoot 'associations.iss'
[System.IO.File]::WriteAllLines($out, $lines, (New-Object System.Text.UTF8Encoding $false))
Write-Output ("wrote {0} registry entries to {1}" -f $lines.Count, $out)

